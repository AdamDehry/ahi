  const LANGS = ['en', 'he'];
  const RTL = new Set(['he']);
  const isLang = (v) => LANGS.includes(v);
  /** The first of the system's preferred languages that AHI speaks, else English ("iw" is Hebrew's old code). */
  const systemLang = (list) => {
    for (const l of list || []) {
      const base = String(l || '').toLowerCase().split(/[-_]/)[0];
      if (base === 'iw') return 'he';
      if (isLang(base)) return base;
    }
    return 'en';
  };
  /** `{name}` placeholders; in Hebrew each value is bidi-isolated so a Latin path or number keeps its direction. */
  const t = (lang, key, params) => {
    const l = isLang(lang) ? lang : 'en';
    const text = STRINGS[l][key] ?? STRINGS.en[key] ?? key;
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (whole, name) => (name in params ? (RTL.has(l) ? `⁨${params[name]}⁩` : String(params[name])) : whole));
  };
  /** Set lang/dir on the page and fill every [data-i18n] element. */
  const apply = (lang, doc) => {
    const l = isLang(lang) ? lang : 'en';
    doc.documentElement.lang = l;
    doc.documentElement.dir = RTL.has(l) ? 'rtl' : 'ltr';
    for (const el of doc.querySelectorAll('[data-i18n]')) el.textContent = t(l, el.dataset.i18n);
  };
  const api = { STRINGS, LANGS, isLang, isRtl: (l) => RTL.has(l), systemLang, t, apply };
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.AHI_I18N = api;
